import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('TV follows the selected wheel, waits after confirmation, and returns to the ranking', async ({ browser, page, request }) => {
  const name = `TV wheels ${randomUUID()}`;
  const event = await (await request.post('/api/tournaments', { data: { name, pin: '1234' } })).json();
  const root = `/api/tournaments/${event.id}`, admin = { Authorization: `Bearer ${event.token}` };
  const player = (await (await request.post(`${root}/participants`, { headers: admin, data: { displayName: 'Alice' } })).json()).id;
  const first = (await (await request.post(`${root}/stages`, { headers: admin, data: { name: 'Qualifiers', kind: 'two-station', participantCount: 1 } })).json()).id;
  await request.post(`${root}/stages`, { headers: admin, data: { name: 'Final', kind: 'elimination', participantCount: 1 } });
  const base = `${root}/stages/${first}`;
  await request.put(`${base}/settings`, { headers: admin, data: { stations: [{ games: [{ name: 'Galaga', developer: 'Namco', resultKind: 'score', higherIsBetter: true, attempts: 1 }] }, { games: [{ name: 'Out Run', resultKind: 'score', higherIsBetter: true, attempts: 1 }] }], points: [5] } });
  const tv = await browser.newPage(); await tv.goto(`/display/${event.id}`);
  await expect(tv.getByRole('region', { name: 'Combined leaderboard' })).toBeVisible();
  await page.goto('/'); await page.getByRole('button', { name, exact: true }).click();
  await page.getByRole('button', { name: 'Wheel 1', exact: true }).click();
  let tvWheel = tv.getByRole('region', { name: 'Station 1 wheel' });
  await expect(tvWheel).toBeVisible(); await expect(tv.getByRole('button')).toHaveCount(0);
  const operatorWheel = page.getByRole('region', { name: 'Station 1 wheel' });
  await operatorWheel.getByRole('button', { name: 'Spin', exact: true }).click();
  await expect(tvWheel.getByText('Spinning…')).toBeVisible();
  await expect(operatorWheel.getByText('Drawn: Galaga')).toBeVisible({ timeout: 10000 });
  await expect(tvWheel.getByText('Drawn: Galaga')).toBeVisible({ timeout: 10000 });
  await operatorWheel.getByRole('button', { name: 'Confirm game' }).click();
  await expect(tvWheel.getByText('Selected: Galaga')).toBeVisible();
  await expect(tvWheel.getByRole('region', { name: 'Selected game information' })).toContainText('Namco');
  await expect(tv.getByRole('region', { name: 'Station 2 wheel' })).toHaveCount(0);
  await tv.reload(); tvWheel = tv.getByRole('region', { name: 'Station 1 wheel' });
  await expect(tvWheel.getByText('Selected: Galaga')).toBeVisible();
  await page.getByRole('button', { name: 'Wheel 2', exact: true }).click();
  await expect(tv.getByRole('region', { name: 'Station 2 wheel' })).toBeVisible();
  await expect(tv.getByRole('region', { name: 'Station 1 wheel' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Leaderboard', exact: true }).click();
  await expect(tv.getByRole('region', { name: 'Combined leaderboard' })).toBeVisible();
  await expect(tv.getByRole('row', { name: /Alice/ })).toBeVisible();
  const rejected = await request.put(`${root}/display-view`, { data: { mode: 'wheel', stageId: first, station: 5 } });
  expect(rejected.status()).toBe(400);
  expect(player).toBeTruthy();
  await tv.close();
});
