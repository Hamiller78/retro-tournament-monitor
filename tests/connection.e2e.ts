import { test, expect } from '@playwright/test';
test('creates a tournament and shares participant updates', async ({ browser, page }) => {
  const name = `Party ${Date.now()}`;
  await page.goto('/'); await expect(page.getByRole('status')).toHaveText('Server: connected');
  await page.getByLabel('Tournament name').fill(name);
  await page.getByLabel('Administrator PIN').fill('1234');
  await page.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(page.getByRole('heading', { name })).toBeVisible();
  const spectator = await browser.newPage(); await spectator.goto('/');
  await spectator.getByRole('button', { name, exact: true }).click();
  await page.getByLabel('Display name').fill('Pixel Hero');
  await page.getByLabel('Real name (optional)').fill('Pat');
  await page.getByRole('button', { name: 'Add participant' }).click();
  await expect(spectator.getByText('Pixel Hero')).toBeVisible();
  await expect(spectator.getByText('Pat', { exact: true })).toHaveCount(0);
  await page.reload();
  await page.getByRole('button', { name: name, exact: true }).click();
  await expect(page.getByText('Administrator access active')).toBeVisible();
  await expect(page.getByText('Pixel Hero').first()).toBeVisible();
  await page.getByLabel('Stage name').fill('Qualifying');
  await page.getByLabel('Number of players (optional)').fill('13');
  await page.getByRole('button', { name: 'Add stage' }).click();
  await expect(spectator.getByText('1. Qualifying', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Game settings Qualifying' }).click();
  await page.getByRole('button', { name: 'Add game to station 1' }).click();
  await page.getByLabel('Game name').fill('Pong');
  await page.getByLabel('Points by finishing position').fill('12, 10, 8');
  await page.getByRole('button', { name: 'Save game settings' }).click();
  await page.getByRole('button', { name: 'Game settings Qualifying' }).click();
  await expect(page.getByLabel('Game name')).toHaveValue('Pong');
  await expect(page.getByLabel('Points by finishing position')).toHaveValue('12, 10, 8');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await spectator.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Wheel 1', exact: true }).click();
  await spectator.getByRole('button', { name: 'Wheel 1', exact: true }).click();
  const wheel = spectator.getByRole('region', { name: 'Station 1 wheel' });
  await wheel.getByRole('button', { name: 'Spin', exact: true }).click();
  await expect(wheel.getByText('Drawn: Pong')).toBeVisible();
  await expect(page.getByRole('region', { name: 'Station 1 wheel' }).getByText('Drawn: Pong')).toBeVisible();
  await wheel.getByRole('button', { name: 'Confirm game' }).click();
  await expect(page.getByRole('region', { name: 'Station 1 wheel' }).getByText('Selected: Pong')).toBeVisible();
  await page.getByRole('button', { name: 'Setup', exact: true }).click();
  await expect(spectator.getByRole('region', { name: 'Station 1 wheel' })).toBeVisible();
  await page.getByLabel('Stage name').fill('Semi-final');
  await page.getByLabel('Stage format').selectOption('elimination');
  await page.getByLabel('Number of players (optional)').fill('4');
  await page.getByRole('button', { name: 'Add stage' }).click();
  await page.getByRole('button', { name: 'Move Semi-final up' }).click();
  await expect(page.locator('section[aria-labelledby="stages-heading"] ol li').first()).toContainText('Semi-final');
  await page.reload();
  await page.getByRole('button', { name, exact: true }).click();
  await expect(page.locator('section[aria-labelledby="stages-heading"] ol li').first()).toContainText('Semi-final');
  await spectator.close();
});
